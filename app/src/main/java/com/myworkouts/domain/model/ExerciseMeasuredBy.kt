package com.myworkouts.domain.model

/**
 * Тип измерения нагрузки в упражнении.
 *
 * `REPS` — упражнение на повторы (подходы × повторения), `TIME` —
 * на время (секунды). Определяет, какое поле будущая форма записи
 * сделает обязательным; слой данных хранит тип, но не валидирует
 * соответствие заполненным полям записи (это ответственность UI).
 */
enum class ExerciseMeasuredBy {
    REPS,
    TIME
}
