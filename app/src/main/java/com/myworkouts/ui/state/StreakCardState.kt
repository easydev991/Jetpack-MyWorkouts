package com.myworkouts.ui.state

/**
 * Состояние карточки серии во вкладке «Активность» (overview-screen).
 *  - [Active] — стрик идёт: показывается оранжевая карточка с огоньком
 *    и счётчиком дней;
 *  - [Pending] — вчера была тренировка, но сегодня ещё не продлили:
 *    карточка остаётся, фон бледный, огонёк приглушён;
 *  - [Lost] — день без тренировки уже прошёл, стрик сломан: вместо
 *    карточки рендерится обычная текстовая строка «Рекорд серии: N дней»
 *    с дефолтными отступами (design D9).
 */
enum class StreakCardState { Active, Pending, Lost }
